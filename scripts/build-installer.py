#!/usr/bin/env python3
"""Build the self-contained installer deterministically from reviewable sources."""
import base64
import gzip
import hashlib
import io
from pathlib import Path
import tarfile
import textwrap

ROOT = Path(__file__).resolve().parents[1]
FILES = {
    'install.sh': 'scripts/install-body.sh',
    'scripts/vpn.py': 'scripts/vpn.py',
    'scripts/renew.sh': 'scripts/renew.sh',
    **{f'config/{name}': f'config/{name}' for name in (
        'certbot-deploy-hook.sh', 'nftables-vpn.conf', '99-vpn-sysctl.conf',
        'strongswan-hardening.conf', 'renew-hardening.conf')},
}


def build():
    archive = io.BytesIO()
    with tarfile.open(fileobj=archive, mode='w', format=tarfile.USTAR_FORMAT) as tar:
        for target, source in sorted(FILES.items()):
            data = (ROOT / source).read_bytes()
            info = tarfile.TarInfo(target)
            info.size = len(data)
            info.mode = 0o600
            info.mtime = 0
            tar.addfile(info, io.BytesIO(data))
    compressed = io.BytesIO()
    with gzip.GzipFile(fileobj=compressed, mode='wb', filename='', mtime=0) as stream:
        stream.write(archive.getvalue())
    payload = compressed.getvalue()
    checksum = hashlib.sha256(payload).hexdigest()
    encoded = '\n'.join(textwrap.wrap(base64.b64encode(payload).decode('ascii'), 76))
    header = '''#!/usr/bin/env bash
# Self-contained IKEv2 VPN installer. No repository checkout or runtime Git fetch.
# Generated by scripts/build-installer.py; edit scripts/install-body.sh and the
# config/scripts sources, then rebuild. The embedded SHA-256 detects corruption,
# not authenticity: download this script over trusted HTTPS.
set -Eeuo pipefail
umask 077
[[ $EUID == 0 ]] || { printf 'Run as root or use sudo bash install.sh.\\n' >&2; exit 1; }
for tool in mktemp base64 sha256sum tar gzip; do
    command -v "$tool" >/dev/null || { printf 'Missing required system tool: %s\\n' "$tool" >&2; exit 1; }
done
PAYLOAD_DIR=$(mktemp -d /tmp/ikev2-vpn.XXXXXX)
trap 'rm -rf -- "$PAYLOAD_DIR"' EXIT
PAYLOAD_SHA256=CHECKSUM
base64 --decode > "$PAYLOAD_DIR/payload.tar.gz" <<'IKEV2_VPN_PAYLOAD'
ENCODED
IKEV2_VPN_PAYLOAD
if ! printf '%s  %s\\n' "$PAYLOAD_SHA256" "$PAYLOAD_DIR/payload.tar.gz" | sha256sum --check --status; then
    printf 'Embedded payload verification failed. Download install.sh again.\\n' >&2
    exit 1
fi
tar --extract --gzip --file "$PAYLOAD_DIR/payload.tar.gz" --directory "$PAYLOAD_DIR" \\
    --no-same-owner --no-same-permissions
if bash "$PAYLOAD_DIR/install.sh"; then
    exit 0
else
    exit "$?"
fi
'''
    return header.replace('CHECKSUM', checksum).replace('ENCODED', encoded)


if __name__ == '__main__':
    output = ROOT / 'install.sh'
    output.write_text(build())
    output.chmod(0o755)
